// To find the radius of the circle 

import java.util.Scanner;

public class areaofcircle{
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        int a=sc.nextInt();
        double b=3.14;
        double area=b*a*a;
        System.out.println("The area of the circle"+area);
    }
}
